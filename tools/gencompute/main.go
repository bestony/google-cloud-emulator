package main

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

type method struct{ name, req, resp string }
type service struct {
	name    string
	methods []method
}

func main() {
	grpcBytes, err := os.ReadFile("gen/google/cloud/compute/v1/compute_grpc.pb.go")
	if err != nil {
		panic(err)
	}
	scaffoldBytes, err := os.ReadFile("products/scaffold/gen_google_cloud_compute_v1.go")
	if err != nil {
		panic(err)
	}

	wanted := map[string]bool{}
	entryRe := regexp.MustCompile(`registerEntry\("google\.cloud\.compute\.v1\.([A-Za-z0-9]+)"`)
	for _, m := range entryRe.FindAllStringSubmatch(string(scaffoldBytes), -1) {
		wanted[m[1]] = true
	}

	ifaceRe := regexp.MustCompile(`^type ([A-Za-z0-9]+)Server interface \{$`)
	methodRe := regexp.MustCompile(`^\t([A-Za-z0-9]+)\(context\.Context, \*([A-Za-z0-9]+)\) \(\*([A-Za-z0-9]+), error\)$`)
	lines := strings.Split(string(grpcBytes), "\n")
	var services []service
	for i := 0; i < len(lines); i++ {
		m := ifaceRe.FindStringSubmatch(strings.TrimRight(lines[i], "\r"))
		if m == nil || strings.HasPrefix(m[1], "Unsafe") || !wanted[m[1]] {
			continue
		}
		svc := service{name: m[1]}
		for i++; i < len(lines) && strings.TrimRight(lines[i], "\r") != "}"; i++ {
			if mm := methodRe.FindStringSubmatch(strings.TrimRight(lines[i], "\r")); mm != nil {
				svc.methods = append(svc.methods, method{mm[1], mm[2], mm[3]})
			}
		}
		if len(svc.methods) == 0 {
			panic("no methods parsed for " + svc.name)
		}
		services = append(services, svc)
	}
	if len(services) != len(wanted) {
		fmt.Fprintf(os.Stderr, "warning: parsed %d services, scaffold has %d\n", len(services), len(wanted))
	}
	sort.Slice(services, func(i, j int) bool { return services[i].name < services[j].name })

	var b strings.Builder
	b.WriteString("// Code generated by tools/gencompute. DO NOT EDIT.\n\npackage compute\n\nimport (\n\t\"context\"\n\n\t\"github.com/grpc-ecosystem/grpc-gateway/v2/runtime\"\n\t\"google.golang.org/grpc\"\n\n\tcomputepb \"github.com/bestony/google-cloud-emulator/gen/google/cloud/compute/v1\"\n)\n\n")
	for _, svc := range services {
		recv := "generic" + svc.name + "Server"
		fmt.Fprintf(&b, "type %s struct {\n\tcomputepb.Unimplemented%sServer\n\thandler *genericComputeHandler\n}\n\n", recv, svc.name)
		for _, me := range svc.methods {
			fmt.Fprintf(&b, "func (s *%s) %s(ctx context.Context, req *computepb.%s) (*computepb.%s, error) {\n\tresp := &computepb.%s{}\n\terr := s.handler.Handle(ctx, %q, %q, req, resp)\n\treturn resp, err\n}\n\n", recv, me.name, me.req, me.resp, me.resp, svc.name, me.name)
		}
	}
	b.WriteString("func registerGenericComputeServices(grpcServer *grpc.Server, gateway *runtime.ServeMux, state *State) error {\n\tctx := context.Background()\n\thandler := newGenericComputeHandler(state)\n")
	for _, svc := range services {
		v := strings.ToLower(svc.name[:1]) + svc.name[1:]
		fmt.Fprintf(&b, "\t%s := &generic%sServer{handler: handler}\n", v, svc.name)
		fmt.Fprintf(&b, "\tcomputepb.Register%sServer(grpcServer, %s)\n", svc.name, v)
		fmt.Fprintf(&b, "\tif err := computepb.Register%sHandlerServer(ctx, gateway, %s); err != nil { return err }\n", svc.name, v)
	}
	b.WriteString("\treturn nil\n}\n")
	if err := os.WriteFile("products/compute/generic_generated.go", []byte(b.String()), 0644); err != nil {
		panic(err)
	}
	fmt.Printf("generated %d compute services\n", len(services))
}
